class AsymmetricVolatilitySignals(BaseSignalFamily):
    def generate_signals(self):
        df = self.df
        df['ret'] = df['Close'].pct_change()
        df['pos_ret'] = df['ret'].clip(lower=0)
        df['neg_ret'] = df['ret'].clip(upper=0)

        def zsc(x, w=252): return (x - x.rolling(w, min_periods=w//2).mean()) / (x.rolling(w, min_periods=w//2).std() + 1e-9)
        def norm(x): return np.tanh(zsc(x, 252))

        # Re-creating formulas logically to avoid eval() namespace issues internally
        # 1. Up_Dn_Vol_Ratio_4_Inv_sm3_High_Vol_Regime_Flash_Crash_Proxy
        raw1 = -norm((df['pos_ret'].rolling(4).std() / (df['neg_ret'].rolling(4).std() + 1e-9)) - 1).rolling(3, min_periods=1).mean()
        raw1 *= np.where(df['ret'].rolling(20).std() > df['ret'].rolling(20).std().rolling(100).mean(), 1, 0)
        raw1 *= np.where((df['ret'] < -0.02) & (df['Volume'] > df['Volume'].rolling(20).mean() * 1.5), 0, 1)
        self.signals['Up_Dn_Vol_Ratio_4_Inv_sm3_High_Vol_Regime_Flash_Crash_Proxy'] = raw1

        # 2. Asym_Vol_Corr_Combo_Avoid_Oversold_ATR_Vol_Scale
        raw2 = norm(zsc(df['pos_ret'].rolling(20).std() - df['neg_ret'].rolling(20).std(), 60) + norm(df['ret'].rolling(10).corr(df['ret'].rolling(10).std())))
        rsi = 100 - (100 / (1 + (df['Close'].diff().where(df['Close'].diff() > 0, 0).rolling(14).mean() / (-df['Close'].diff().where(df['Close'].diff() < 0, 0).rolling(14).mean() + 1e-9))))
        raw2 *= np.where(rsi < 30, 0, 1)
        raw2 *= np.where((df['High']-df['Low']) > (df['High']-df['Low']).rolling(50).mean(), 1.5, 0.5)
        self.signals['Asym_Vol_Corr_Combo_Avoid_Oversold_ATR_Vol_Scale'] = raw2

