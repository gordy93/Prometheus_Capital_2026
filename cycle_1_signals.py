def build_bear_signals(df):
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)

    sma200 = c.rolling(200).mean()
    high252 = h.rolling(252).max()
    dd252 = (c - high252) / (high252 + 1e-8)
    low20 = l.rolling(20).min().shift(1)

    ema12 = c.ewm(span=12, adjust=False).mean()
    ema26 = c.ewm(span=26, adjust=False).mean()
    macd = ema12 - ema26
    macd_sig = macd.ewm(span=9, adjust=False).mean()
    macd_bull = macd > macd_sig
    bear_regime = c < sma200

    # S1
    dist = (c - sma200) / (sma200 + 1e-8)
    s1_base = np.where(dist < 0, -np.clip(dist * 5.0, -1, 1), 0)

    # S2
    s2_base = np.where((dd252 < -0.08) & macd_bull, 1, 0)

    # S3
    vol_thresh = vol20.rolling(252).quantile(0.40)
    s3_base = np.where(bear_regime & (vol20 < vol_thresh) & (c < low20), -1, 0)
    streak_down = (ret < 0) & (ret.shift(1) < 0)
    s3_final = np.where(streak_down, s3_base, 0)

    # S4
    ret_10 = c.pct_change(10)
    s4_base = np.where(bear_regime & (ret_10 < -0.10), 1, 0)

    return {
        'Bear_DistFade_SMA200_Scale5':  pd.Series(s1_base, index=c.index).shift(1).fillna(0),
        'Bear_Capitulation_8_MACDBull': pd.Series(s2_base, index=c.index).shift(1).fillna(0),
        'Bear_LowVol_Breakdown40th':    pd.Series(s3_final, index=c.index).shift(1).fillna(0),
        'Bear_MR_Drop_10d_10':          pd.Series(s4_base, index=c.index).shift(1).fillna(0)
    }

