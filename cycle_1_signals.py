def build_autocorrelation_signals(df):
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)

    ma_200 = c.rolling(200).mean()
    z_5 = (ret - ret.rolling(5).mean()) / (ret.rolling(5).std() + 1e-6)
    vol_pct = vol20.rolling(252).rank(pct=True)
    gap = o / c.shift(1) - 1

    macd = c.ewm(span=12).mean() - c.ewm(span=26).mean()
    macd_sig = macd.ewm(span=9).mean()
    wick = (c - l) / (h - l + 1e-6)

    sign_ret = np.sign(ret)
    sign_change = sign_ret != sign_ret.shift(1)
    run_len_abs = sign_ret.groupby(sign_change.cumsum()).cumcount() + 1
    run_length = run_len_abs * sign_ret

    base1 = pd.Series(np.where((c > ma_200) & (ret < 0), -z_5, 0), index=c.index).clip(0, 1)
    base1 = base1 * np.where(vol20 < vol20.shift(5), 1, 0)
    s1 = (0.5 * base1 + 0.25 * base1.shift(1).fillna(0) + 0.125 * base1.shift(2).fillna(0))

    base2 = pd.Series(np.where((c > ma_200) & (ret < 0), 1, 0), index=c.index)
    base2 = base2 * np.where(vol20 < vol20.shift(5), 1, 0)
    s2 = np.where(gap > 0, base2.clip(-1, 0.5), base2)

    med_vol = vol20.rolling(252).median()
    base3 = pd.Series(np.where(vol20 > med_vol, -np.sign(ret), np.sign(ret)), index=c.index)
    base3 = (base3 + base3.shift(1).fillna(0) + base3.shift(2).fillna(0)) / 3
    s3 = base3 * np.where(c.ewm(span=50).mean() > c.ewm(span=200).mean(), 1, 0)

    base4 = pd.Series(np.where((vol_pct > 0.5) & (ret < 0), 1, 0), index=c.index)
    base4 = base4 * np.where(np.sign(gap) != np.sign(base4), 1, 0)
    s4 = base4.ewm(span=5).mean()

    sigA = np.where((vol_pct > 0.5) & (vol_pct <= 0.75) & (ret < 0), 1, 0)
    sigB = np.where((vol_pct > 0.75) & (run_length >= 2), -1, 0)
    sigC = np.where((vol_pct <= 0.5), np.sign(ret), 0)
    base5 = pd.Series(sigA + sigB + sigC, index=c.index).clip(-1, 1)
    base5 = base5 * np.where(wick > 0.5, 1, 0)
    s5 = base5.ewm(span=5).mean()

    vol_ma = v.rolling(20).mean()
    base6 = pd.Series(np.where((ret < 0) & (v <= vol_ma), 1, 0), index=c.index)
    s6 = base6.ewm(span=5).mean()

    streak = (ret < 0) & (ret.shift(1) < 0) & (ret.shift(2) < 0)
    base7 = pd.Series(np.where((c > ma_200) & streak & (macd > macd_sig), 1, 0), index=c.index)
    ac = ret.rolling(20).corr(ret.shift(1))
    s7 = base7 * np.where(ac.diff() > 0, 1, 0)

    return {
        'ACOR_UpTrend_DipScale_Dyn': pd.Series(s1, index=c.index).shift(1).fillna(0),
        'ACOR_UpTrend_DipBuy_Gap':   pd.Series(s2, index=c.index).shift(1).fillna(0),
        'ACOR_VolCond_EMA_Cross':    pd.Series(s3, index=c.index).shift(1).fillna(0),
        'ACOR_HighVol_DipBuy_EMA5':  pd.Series(s4, index=c.index).shift(1).fillna(0),
        'ACOR_Ensemble_Wick_EMA5':   pd.Series(s5, index=c.index).shift(1).fillna(0),
        'ACOR_AsymRev_VolDry_EMA5':  pd.Series(s6, index=c.index).shift(1).fillna(0),
        'ACOR_UpTrend_Dn3_MACD':     pd.Series(s7, index=c.index).shift(1).fillna(0)
    }

