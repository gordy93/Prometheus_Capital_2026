def build_volume_signals(df):
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)

    chop14 = calc_chop(h, l, c, 14)
    rsi14 = calc_rsi(c, 14)
    roll_max14 = c.rolling(14).max()
    ulcer = np.sqrt((((c - roll_max14) / roll_max14 * 100)**2).rolling(14).mean())
    gap = (o / c.shift(1) - 1).abs()

    b1 = tanh_clip(v.pct_change(5) * np.sign(ret))
    v_climax = v > v.rolling(252).quantile(0.95)
    sig_1 = np.where(v_climax, -b1, b1) * (chop14 < 50)

    v_scale = v / v.rolling(50).mean()
    b2 = tanh_clip(zscore(ret, 20) * (v / v.rolling(20).mean() - 1.25))
    sig_2 = np.clip(b2 * v_scale, -1, 1) / (ulcer + 1)

    b3 = tanh_clip(zscore(c, 10)) * np.clip(zscore(v, 10), 0, 1)
    sig_3 = b3 * (c < c.rolling(50).mean()) * (gap < 0.005)

    b4 = tanh_clip(zscore(v, 10) * np.sign(ret))
    s4_temp = np.where(b4 > 0, b4, b4 * 0.5)
    sig_4 = np.where((rsi14 > 80) & (s4_temp > 0), -s4_temp, np.where((rsi14 < 20) & (s4_temp < 0), -s4_temp, s4_temp))

    mfm = ((c - l) - (h - c)) / (h - l + 1e-8)
    cmf10 = (mfm * v).rolling(10).sum() / (v.rolling(10).sum() + 1e-8)
    s5_temp = cmf10 * np.sign(v - v.shift(1))
    sig_5 = np.where(s5_temp < 0, s5_temp * 0.25, s5_temp)

    return {
        "Vol_01_VROC_ClimaxFade": pd.Series(sig_1, index=c.index).shift(1).fillna(0),
        "Vol_02_ZThresh_Scale":   pd.Series(sig_2, index=c.index).shift(1).fillna(0),
        "Vol_03_PVTrend_Gap":     pd.Series(sig_3, index=c.index).shift(1).fillna(0),
        "Vol_04_ZMom_ExtremeRSI": pd.Series(sig_4, index=c.index).shift(1).fillna(0),
        "Vol_05_CMF_Accel":       pd.Series(sig_5, index=c.index).shift(1).fillna(0)}

