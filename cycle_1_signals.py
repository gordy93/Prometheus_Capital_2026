def build_seasonal_signals(df):
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)
    month = df.index.month
    t_to_eom = df.groupby([df.index.year, df.index.month]).cumcount(ascending=False)
    t_from_bom = df.groupby([df.index.year, df.index.month]).cumcount(ascending=True)

    cal = USFederalHolidayCalendar()
    holidays = cal.holidays(start=df.index.min(), end=df.index.max())
    is_pre_hol = pd.Series([
        1 if (d + pd.Timedelta(days=1) in holidays or
              d + pd.Timedelta(days=2) in holidays or
             (d + pd.Timedelta(days=3) in holidays and d.dayofweek == 4)) else 0
        for d in df.index
    ], index=df.index)

    sma50 = c.rolling(50).mean()
    sma100 = c.rolling(100).mean()
    clv = ((c - l) - (h - c)) / (h - l + 1e-8)
    bb_width = (c.rolling(20).std() * 4) / c.rolling(20).mean()
    er10 = calc_er(c, 10)

    b_tom = np.where((t_to_eom <= 3) | (t_from_bom <= 3), 1, 0)
    sig_tom = pd.Series(b_tom, index=c.index).shift(1) * (vol20 >= vol60).astype(int)

    b_jan = np.where((month == 1) & (c < sma50), 1, 0)
    sig_jan = b_jan * (clv > 0).astype(int)

    b_dec = np.where((month == 12) & (t_to_eom <= 10), 1, 0)
    sig_dec = pd.Series(b_dec, index=c.index).shift(1) * (vol20 < vol60).astype(int)

    b_rob = np.where(np.isin(month,[7, 11, 12]), 1, np.where(month == 6, -1, 0))
    sig_rob = b_rob * (bb_width < bb_width.rolling(252).median()).astype(int) * (er10 <= 0.5).astype(int)

    sig_pre = is_pre_hol * (c > sma100).astype(int)

    return {
        'Sea_TOM_VolExp':      pd.Series(sig_tom, index=c.index).shift(1).fillna(0),
        'Sea_Jan_MeanRev':     pd.Series(sig_jan, index=c.index).shift(1).fillna(0),
        'Sea_Dec_VolContr':    pd.Series(sig_dec, index=c.index).shift(1).fillna(0),
        'Sea_RobustM_BBSqz':   pd.Series(sig_rob, index=c.index).shift(1).fillna(0),
        'Sea_PreHol_Trend100': pd.Series(sig_pre, index=c.index).shift(1).fillna(0)
    }

