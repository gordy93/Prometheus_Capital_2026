    sig_3_c2 = c > sma20
    sig_3_c3 = (h - l) > atr14
    sig_3_z = (c - sma20) / (c.rolling(20).std() + 1e-8)
    sig_3_c4 = sig_3_z < 2.0
    sig_3_base = np.where(sig_3_c1, np.where(sig_3_c2, 1, -1), 0)
