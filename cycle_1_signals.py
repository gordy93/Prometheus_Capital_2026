def compute_base(df):
    c = df["Close"]
    h = df["High"]
    l = df["Low"]
    v = df["Volume"]
    o = df["Open"]

    ret = c.pct_change()
    tr = np.maximum(h - l, np.maximum((h - c.shift(1)).abs(), (l - c.shift(1)).abs()))

    vol20 = ret.rolling(20).std() * np.sqrt(252)
    vol60 = ret.rolling(60).std() * np.sqrt(252)
    vol_adj = (0.15 / (vol20 + 1e-8)).replace([np.inf, -np.inf], np.nan).fillna(1).clip(0.5, 2.0)

    return o, h, l, c, v, ret, tr, vol20, vol60, vol_adj

def calc_rsi(series, period):
    delta = series.diff()
    gain = delta.where(delta > 0, 0).rolling(period).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(period).mean()
    rs = gain / (loss + 1e-8)
    return 100 - (100 / (1 + rs))

def calc_chop(h, l, c, period):
    tr = np.maximum(h - l, np.maximum((h - c.shift(1)).abs(), (l - c.shift(1)).abs()))
    sum_tr = tr.rolling(period).sum()
    highest = h.rolling(period).max()
    lowest = l.rolling(period).min()
    return 100 * np.log10(sum_tr / (highest - lowest + 1e-8)) / np.log10(period)

def calc_er(c, period):
    change = c.diff(period).abs()
    volatility = c.diff().abs().rolling(period).sum()
    return change / (volatility + 1e-8)

def zscore(series, period):
    return (series - series.rolling(period).mean()) / (series.rolling(period).std() + 1e-8)

def tanh_clip(series, scale=1.0):
    return np.tanh(series / scale)

