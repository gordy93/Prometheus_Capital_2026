        raw3 = norm((df['pos_ret'].ewm(span=10).std() - df['neg_ret'].ewm(span=10).std()) / (df['pos_ret'].ewm(span=10).std() + df['neg_ret'].ewm(span=10).std() + 1e-9))
        raw3 *= np.where(df['Close'].pct_change(5) > 0, 1, 0)
        raw3 *= np.where((df['High']-df['Low']) > (df['High']-df['Low']).rolling(50).mean(), 1.5, 0.5)
        self.signals['EWMA_Vol_Asym_10_5D_Trend_Filter_ATR_Vol_Scale'] = raw3

        # 4. Semi_Vol_Z_Spread_Avoid_Oversold_Wide_Range
        raw4 = norm(zsc(df['pos_ret'].rolling(20).std(), 60) - zsc(df['neg_ret'].rolling(20).std(), 60))
        raw4 *= np.where(rsi < 30, 0, 1)
        raw4 *= np.where((df['High'] - df['Low']) > (df['High'] - df['Low']).rolling(20).mean() * 1.5, 1.5, 0.5)
        self.signals['Semi_Vol_Z_Spread_Avoid_Oversold_Wide_Range'] = raw4


