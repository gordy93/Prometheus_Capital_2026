    sma5 = c.rolling(5).mean()
    sma20 = c.rolling(20).mean()
    sma60 = c.rolling(60).mean()

    rv10 = ret.rolling(10).std() * np.sqrt(252)
    rv20 = ret.rolling(20).std() * np.sqrt(252)
    rv60 = ret.rolling(60).std() * np.sqrt(252)
    rv252 = ret.rolling(252).std() * np.sqrt(252)

    rv20_pct = rv20.rolling(252).rank(pct=True)
    ts10_60 = rv10 / (rv60 + 1e-8)
    rv60_roc20 = rv60.pct_change(20)
    atr14 = (h - l).rolling(14).mean()

    # S1
    s1_base = np.where((rv20_pct < 0.40) & (c > sma20) & (rv252 < rv252.shift(60)), 1, 0)
    s1_vol_target = np.clip(0.10 / (rv20 + 1e-8), 0, 1)
    s1 = s1_base * s1_vol_target

    # S5
    s5_base = np.where(rv20_pct < 0.40, np.where(c > sma20, 1, -1), 0)
    s5 = s5_base * np.where((rv60_roc20 < 0) & (rv252 < rv252.shift(60)), 1, 0)

    # S8
    s8_c1 = rv20_pct < 0.50
    s8_c2 = c > sma20
    s8_c3 = (h - l) > atr14
    s8_z = (c - sma20) / (c.rolling(20).std() + 1e-8)
    s8_c4 = s8_z < 2.0
    s8_base = np.where(s8_c1, np.where(s8_c2, 1, -1), 0)
    s8 = s8_base * np.where(s8_c3 & s8_c4, 1, 0)

    # S9
    s9_c1 = ts10_60 < 0.70
    s9_c2 = c > sma5
    s9_c3 = c < sma60
    s9_base = np.where(s9_c1 & s9_c3, np.where(s9_c2, 1, -1), 0)
    atr_norm = (atr14.rolling(252).min() / (atr14 + 1e-8)).clip(0, 1)
    s9 = s9_base * atr_norm

    return {
        'LRV_Trend_VolTarget':    pd.Series(s1, index=c.index).shift(1).fillna(0),
        'LRV_SymTrend_MacroCont': pd.Series(s5, index=c.index).shift(1).fillna(0),
        'LRV_SymTrend_ATRExp':    pd.Series(s8, index=c.index).shift(1).fillna(0),
        'LRV_TermStruct_MeanRev': pd.Series(s9, index=c.index).shift(1).fillna(0)
    }

