def build_volume_signals(df):
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)
    chop14 = calc_chop(h, l, c, 14)
    rsi14 = calc_rsi(c, 14)
    roll_max14 = c.rolling(14).max()
    ulcer = np.sqrt((((c - roll_max14) / roll_max14 * 100)**2).rolling(14).mean())
    gap = (o / c.shift(1) - 1).abs()

    b1 = tanh_clip(v.pct_change(5) * np.sign(ret))
    v_climax = v > v.rolling(252).quantile(0.95)
    s1 = np.where(v_climax, -b1, b1) * (chop14 < 50)

    v_scale = v / v.rolling(50).mean()
    b2 = tanh_clip(zscore(ret, 20) * (v / v.rolling(20).mean() - 1.25))
    s2 = np.clip(b2 * v_scale, -1, 1) / (ulcer + 1)

    b3 = tanh_clip(zscore(c, 10)) * np.clip(zscore(v, 10), 0, 1)
    s3 = b3 * (c < c.rolling(50).mean()) * (gap < 0.005)

    b4 = tanh_clip(zscore(v, 10) * np.sign(ret))
    s4 = np.where(b4 > 0, b4, b4 * 0.5)
    s4 = np.where((rsi14 > 80) & (s4 > 0), -s4, np.where((rsi14 < 20) & (s4 < 0), -s4, s4))

    mfm = ((c - l) - (h - c)) / (h - l + 1e-8)
    cmf10 = (mfm * v).rolling(10).sum() / (v.rolling(10).sum() + 1e-8)
    s5 = cmf10 * np.sign(v - v.shift(1))
    s5 = np.where(s5 < 0, s5 * 0.25, s5)

    return {
        'Vol_VROC_ClimaxFade': pd.Series(s1, index=c.index).shift(1).fillna(0),
        'Vol_ZThresh_Scale':   pd.Series(s2, index=c.index).shift(1).fillna(0),
        'Vol_PVTrend_Gap':     pd.Series(s3, index=c.index).shift(1).fillna(0),
        'Vol_ZMom_ExtremeRSI': pd.Series(s4, index=c.index).shift(1).fillna(0),
        'Vol_CMF_Accel':       pd.Series(s5, index=c.index).shift(1).fillna(0)
    }

