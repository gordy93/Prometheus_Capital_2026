class HurstExponentSignals(BaseSignalFamily):
    def generate_signals(self):
        df = self.df
        df['Ret'] = df['Close'].pct_change()

        def calc_rs_hurst(prices, window):
            log_ret = np.log(prices).diff().fillna(0).values
            h_vals = np.zeros(len(log_ret))
            for i in range(window, len(log_ret)):
                x = log_ret[i-window:i]
                S = np.std(x, ddof=0)
                if S == 0:
                    h_vals[i] = 0.5
                    continue
                cum_y = np.cumsum(x - np.mean(x))
                R = np.max(cum_y) - np.min(cum_y)
                h_vals[i] = np.log(R/S) / np.log(window) if R != 0 else 0.5
            return pd.Series(h_vals, index=prices.index).replace(0, 0.5)

        h20 = calc_rs_hurst(df['Close'], 20)
        h40 = calc_rs_hurst(df['Close'], 40)
        h60 = calc_rs_hurst(df['Close'], 60)
        h120 = calc_rs_hurst(df['Close'], 120)

        diff = df['Close'].diff(1)
        rsi14 = 100 - (100 / (1 + diff.where(diff > 0, 0).rolling(14).mean() / -diff.where(diff < 0, 0).rolling(14).mean()))

        sma20 = df['Close'].rolling(20).mean()
        sma40 = df['Close'].rolling(40).mean()

        vol_ratio = df['Volume'] / df['Volume'].rolling(20).mean()
        mf_mult = ((df['Close'] - df['Low']) - (df['High'] - df['Close'])) / (df['High'] - df['Low'] + 1e-8)
        cmf = (mf_mult * df['Volume']).rolling(20).sum() / (df['Volume'].rolling(20).sum() + 1e-8)
        h_20_120_z = (h20 - h120) / h20.rolling(252).std()
        tr = np.maximum(df['High'] - df['Low'], np.maximum(abs(df['High']-df['Close'].shift()), abs(df['Low']-df['Close'].shift())))
        chop = 100 * np.log10(tr.rolling(14).sum() / (df['High'].rolling(14).max() - df['Low'].rolling(14).min() + 1e-8)) / np.log10(14)

        sig2 = pd.Series(0, index=df.index)
        sig2[(h20 < 0.45) & (rsi14 < 20)] = 1
        sig2[(h20 < 0.45) & (rsi14 > 80)] = -1
        sig2[df.index.dayofweek == 0] = 0
        sig2[(sig2 < 0) & (df['Ret'] < 0)] = 0
        self.signals['S2_HurstRSIFade'] = sig2

        sig3 = pd.Series(0, index=df.index)
        sig3[(h20 - h60) > 0.015] = np.sign(df['Close'] - sma20)
        sig3[(h20 - h60) < -0.015] = -np.sign(df['Close'] - sma20)
        sig3[sig3 < 0] *= 0.5
        sig3[(sig3 < 0) & (df['Ret'] < 0)] = 0
        self.signals['S3_HurstSlope_AsymUp'] = sig3

        sig5 = pd.Series(0, index=df.index)
        sig5[(h20 - h60) > 0.02] = np.sign(df['Close'] - sma20)
        sig5[(h20 - h60) < -0.02] = -np.sign(df['Close'] - sma20)
        sig5[sig5 < 0] *= 0.5
        sig5[sig5 < 0] *= np.clip(1 - vol_ratio, 0, 1)[sig5 < 0]
        self.signals['S5_HurstSlope_VolScale'] = sig5

        sig6 = pd.Series(0, index=df.index)
        sig6[(h40 - h60) > 0.04] = np.sign(df['Close'] - sma20)
        sig6[(h40 - h60) < -0.04] = -np.sign(df['Close'] - sma20)
        sig6[df.index.dayofweek == 0] = 0
        sig6[h_20_120_z > 2.0] = -sig6[h_20_120_z > 2.0]
        self.signals['S6_HurstSlope_InvZ'] = sig6

        sig7 = pd.Series(0, index=df.index)
        sig7[(h40 - h120) > 0.05] = np.sign(df['Close'] - sma40)
        sig7[(h40 - h120) < -0.05] = -np.sign(df['Close'] - sma40)
        sig7[np.log(df['Close']).diff().rolling(20).std() > np.log(df['Close']).diff().rolling(120).std()] = 0
        sig7[chop < 40] = 0
        self.signals['S7_HurstSlope_VolSq'] = sig7

        sig9 = pd.Series(0, index=df.index)
        sig9[(h20 - h60) > 0.03] = np.sign(df['Close'] - sma20)
        sig9[(h20 - h60) < -0.03] = -np.sign(df['Close'] - sma20)
        sig9[sig9 < 0] *= 0.5
        sig9[(sig9 > 0) & (cmf < 0)] = 0
        sig9[(sig9 < 0) & (cmf > 0)] = 0
        self.signals['S9_HurstSlope_CMF'] = sig9

        sig10 = pd.Series(0, index=df.index)
        sig10[(h20 - h120) > 0.02] = np.sign(df['Close'] - sma20)
        sig10[(h20 - h120) < -0.02] = -np.sign(df['Close'] - sma20)
        sig10[(sig10 > 0) & (df['Close'] < df['Low'].rolling(5).min().shift(1))] = 0
        sig10[(sig10 < 0) & (df['Close'] > df['High'].rolling(5).max().shift(1))] = 0
        sig10[sig10 < 0] *= np.clip(1 - vol_ratio, 0, 1)[sig10 < 0]
        self.signals['S10_HurstSlope_Trail'] = sig10


