def build_fibonacci_signals(df):
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)

    rsi14 = calc_rsi(c, 14)
    bouncing = c > c.shift(1)

    pdm = np.where((h - h.shift(1)) > (l.shift(1) - l), np.maximum(h - h.shift(1), 0), 0)
    mdm = np.where((l.shift(1) - l) > (h - h.shift(1)), np.maximum(l.shift(1) - l, 0), 0)
    atr_adx = tr.rolling(14).mean()
    pdi = 100 * (pd.Series(pdm, index=c.index).rolling(14).mean() / atr_adx)
    mdi = 100 * (pd.Series(mdm, index=c.index).rolling(14).mean() / atr_adx)
    adx = (100 * abs(pdi - mdi) / (pdi + mdi + 1e-8)).rolling(14).mean()

    idx = np.arange(len(df))
    fibs = {}
    for w in[20, 60, 120, 252]:
        sh = h.rolling(w).max()
        sl = l.rolling(w).min()
        sh_idx = h.rolling(w).apply(np.argmax, raw=True) + idx - w + 1
        sl_idx = l.rolling(w).apply(np.argmin, raw=True) + idx - w + 1
        sdir = np.where(sh_idx > sl_idx, 1, -1)
        amp = sh - sl
        st = (c - sl) / (amp + 1e-8)
        fibs[w] = {"st": st, "sdir": sdir, "amp": amp, "sh": sh, "sl": sl}

    s1_cond = (fibs[120]["st"] > 0.382) & (fibs[120]["st"] < 0.618) & bouncing
    sig_1 = pd.Series(s1_cond, index=c.index).rolling(3).mean().fillna(0) * (rsi14 < 70) * (((c - l) / (h - l + 1e-8)) > 0.70)

    cg = sum(np.where((fibs[w]["st"] > 0.382) & (fibs[w]["st"] < 0.618) & bouncing, 1, 0) for w in [20, 60, 120, 252])
    sig_2 = pd.Series(cg / 4, index=c.index).rolling(3).mean().fillna(0) * (rsi14 < 70) * (adx / 100)

    s3_cond = (fibs[252]["st"] > 0) & (fibs[252]["st"] <= 0.382) & bouncing
    sig_3 = pd.Series(s3_cond, index=c.index).rolling(3).mean().fillna(0) * (rsi14 < 70) * (adx / 100)

    f0618 = np.where(fibs[20]["sdir"] == 1, fibs[20]["sh"] - 0.618 * fibs[20]["amp"], fibs[20]["sl"] + 0.618 * fibs[20]["amp"])
    c4l = (fibs[252]["sdir"] == 1) & (fibs[20]["sdir"] == -1) & (c > f0618)
    c4s = (fibs[252]["sdir"] == -1) & (fibs[20]["sdir"] == 1) & (c < f0618)
    sig_4 = np.where(c4l, 1, np.where(c4s, -1, 0)) * (c.pct_change(20) < 0) * (adx / 100)

    s5_cond = (fibs[120]["st"] > 0) & (fibs[120]["st"] <= 0.382) & bouncing
    sig_5 = pd.Series(s5_cond, index=c.index).rolling(3).mean().fillna(0) * (ret < 0) * (adx / 100)

    return {
        "Fib_01_GoldenBounce120": pd.Series(sig_1, index=c.index).shift(1).fillna(0),
        "Fib_02_ComboGolden_ADX": pd.Series(sig_2, index=c.index).shift(1).fillna(0),
        "Fib_03_DeepPull252_ADX": pd.Series(sig_3, index=c.index).shift(1).fillna(0),
        "Fib_04_MTF_Divergence":  pd.Series(sig_4, index=c.index).shift(1).fillna(0),
        "Fib_05_DeepPull120_Red": pd.Series(sig_5, index=c.index).shift(1).fillna(0)}

