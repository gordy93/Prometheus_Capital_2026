    sig_4_c1 = ts10_60 < 0.70
    sig_4_c2 = c > sma5
    sig_4_c3 = c < sma60
    sig_4_base = np.where(sig_4_c1 & sig_4_c3, np.where(sig_4_c2, 1, -1), 0)
    atr_norm = (atr14.rolling(252).min() / (atr14 + 1e-8)).clip(0, 1)
    sig_4 = sig_4_base * atr_norm

