def build_macro_breadth_signals(df):
    if 'Close_GDX' not in df.columns: return {}
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)
    signals = {}

    # -- GROUP A --
    r_gdx = df['Close_GDX'].pct_change()
    r_eur = df['Close_EUR'].pct_change()
    r_vix = df['Close_VIX'].pct_change()

    base_sig_10 = (zscore(df['Close_GDX']/c, 10) / 3).clip(-1, 1)
    eur_trend = (df['Close_EUR'] > df['Close_EUR'].rolling(20).mean()).astype(int)
    comp_ret = r_gdx + r_eur - r_vix
    vol_exp = (vol20 > ret.rolling(100).std() * np.sqrt(252)).astype(int)
    panic = ((r_gdx < -0.01) & (r_eur < -0.005) & (r_vix > 0.05)).astype(int).rolling(10).max().fillna(0)

    sA1 = np.sign((base_sig_10 + 0.5 * eur_trend).clip(-1, 1)) * (ret < 0.01) * (r_gdx.rolling(10).sum() > 0)
    sA2 = np.where(((base_sig_10 + panic).clip(-1, 1) * vol_exp < 0) & (df['Close_VIX'] > 20), 0, (base_sig_10 + panic).clip(-1, 1) * vol_exp)

    sA3_raw = (zscore(comp_ret, 50) / 3).clip(-1, 1) * (vol20 > vol20.rolling(50).mean()) * (ret.rolling(50).skew() < 0)
    sA3 = np.where((sA3_raw > 0) & (df['Close_VIX'] > 25), sA3_raw * 2, sA3_raw).clip(-1, 1)

    sA4 = ((comp_ret > 0).rolling(20).sum() - 10) / 5
    sA4 = (sA4 + panic).clip(-1, 1) * vol_exp * ((ret > 0).rolling(3).sum() <= 1)
    sA5 = np.where(df['Close_EUR'] < df['Close_EUR'].rolling(50).mean(), panic * (ret.rolling(50).corr(r_gdx) > 0.85) * 0.5, panic * (ret.rolling(50).corr(r_gdx) > 0.85))

    signals.update({
        'MacA_GDX_TrendMiner': pd.Series(sA1, index=c.index).shift(1).fillna(0),
        'MacA_Ratio_Panic':    pd.Series(sA2, index=c.index).shift(1).fillna(0),
        'MacA_CompBreadth':    pd.Series(sA3, index=c.index).shift(1).fillna(0),
        'MacA_EcoDays':        pd.Series(sA4, index=c.index).shift(1).fillna(0),
        'MacA_PurePanic':      pd.Series(sA5, index=c.index).shift(1).fillna(0)
    })

    # -- GROUP B --
    r_spx = df['Close_SPX'].pct_change()
    r_ndx = df['Close_NDX'].pct_change()
    r_u10 = df['Close_US10Y'].pct_change()

    adl = (np.sign(r_spx) + np.sign(r_ndx) + np.sign(r_u10)).cumsum()
    sB1 = np.maximum(0, (adl > adl.rolling(20).mean()).astype(int) * 2 - 1)

    spx_bear = df['Close_SPX'] < df['Close_SPX'].rolling(200).mean()
    sB2_base = (r_spx.rolling(20).corr(r_u10) > 0).astype(int) * 2 - 1
    sB2 = np.where(sB2_base < 0, np.where(spx_bear, sB2_base, 0), sB2_base)

    sB3 = ((df['Close_NDX']/df['Close_SPX']).pct_change(200) > 0) & (df['Close_US10Y'].pct_change(200) < 0)
    sB3 = sB3 * ((df['Close_NDX']/df['Close_SPX']).pct_change(20) > 0)

    sB4_base = (np.sign(r_spx) + np.sign(r_ndx) + np.sign(r_u10)).rolling(20).mean() / 3.0
    sB4 = np.where(sB4_base < 0, np.where(spx_bear, sB4_base, 0), sB4_base)

    adv = (r_spx > 0).astype(int) + (r_ndx > 0).astype(int) + (r_u10 > 0).astype(int) + (ret > 0).astype(int)
    sB5_base = (adv / 4.0).rolling(20).mean() * 2 - 1
    ribbon = (c.rolling(10).mean() > c.rolling(20).mean()) & (c.rolling(20).mean() > c.rolling(50).mean())
    sB5 = sB5_base * ribbon

    signals.update({
        'MacB_ADL_LongOnly':   pd.Series(sB1, index=c.index).shift(1).fillna(0),
        'MacB_Corr_SPXBear':   pd.Series(sB2, index=c.index).shift(1).fillna(0),
        'MacB_TechOutperf':    pd.Series(sB3, index=c.index).shift(1).fillna(0),
        'MacB_SmBreadthBear':  pd.Series(sB4, index=c.index).shift(1).fillna(0),
        'MacB_PropAdv_Ribbon': pd.Series(sB5, index=c.index).shift(1).fillna(0)
    })

    # -- GROUP C --
    r2_cu = df['Close_Copper'].pct_change(2)
    r2_u2 = df['Close_US2Y'].pct_change(2)
    r2_vv = df['Close_VVIX'].pct_change(2)
    vv_norm = df['Close_VVIX'] / df['Close_VVIX'].rolling(252).mean()

    sC1_b = np.where((np.sign(r2_cu) == -1) & (np.sign(r2_u2) == -1), 1, np.where((np.sign(r2_cu) == 1) & (np.sign(r2_u2) == 1) & (np.sign(r2_vv) == 1), -1, 0))
    sC1 = np.where(sC1_b > 0, sC1_b * vv_norm, 0)

    cu_u2 = df['Close_Copper'] / df['Close_US2Y']
    sC2 = np.where(c > c.rolling(200).mean(), np.sign(cu_u2 - cu_u2.rolling(100).mean()), 0)

    br_c = (df['Close_Copper'] > df['Close_Copper'].rolling(50).mean()).astype(int) + (df['Close_US2Y'] < df['Close_US2Y'].rolling(50).mean()).astype(int) + (df['Close_VVIX'] < df['Close_VVIX'].rolling(50).mean()).astype(int)
    sC3 = np.where((df.index.dayofweek != 4) & (br_c >= 1) & (c > c.rolling(50).mean()), 1, 0)

    rr_10 = zscore(df['Close_US2Y'], 10) - zscore(df['Close_Copper'], 10)
    sC4 = pd.Series(np.where(rr_10 < rr_10.rolling(10).mean(), 1, -1)).ewm(span=3).mean()
    sC4 = np.where(df.index.dayofweek == 4, 0, np.where(sC4 > 0, sC4, 0))

    rr_50 = zscore(df['Close_US2Y'], 50) - zscore(df['Close_Copper'], 50)
    sC5 = pd.Series(np.where(rr_50 < rr_50.rolling(50).mean(), 1, -1)).rolling(5).mean()
    sC5 = np.where(sC5 > 0, sC5, 0) * (df['Close_US2Y'] / df['Close_US2Y'].rolling(200).mean())

    signals.update({
        'MacC_W2Rev_VVIX':     pd.Series(sC1, index=c.index).clip(-1, 1).shift(1).fillna(0),
        'MacC_CuU2_GLDBull':   pd.Series(sC2, index=c.index).clip(-1, 1).shift(1).fillna(0),
        'MacC_FiltB2_NoFri':   pd.Series(sC3, index=c.index).clip(-1, 1).shift(1).fillna(0),
        'MacC_RR10_EMA3_Long': pd.Series(sC4, index=c.index).clip(-1, 1).shift(1).fillna(0),
        'MacC_RR50_ScaleU2':   pd.Series(sC5, index=c.index).clip(-1, 1).shift(1).fillna(0)
    })

    return signals

