def build_rates_fx_signals(df):
    if 'Close_US10Y' not in df.columns: return {}
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)
    signals = {}

    u10 = df['Close_US10Y']
    u2 = df['Close_US2Y']
    eur = df['Close_EUR']
    uj = df['Close_UJ']

    # -- US10Y --
    rsi_diff = calc_rsi(c, 9) - calc_rsi(u10, 9)
    s10_2 = np.where(vol20 < vol20.rolling(277).median(), np.tanh(zscore(rsi_diff, 55)), 0).clip(0, 1)

    z_rr3 = zscore(c * u10, 11)
    b3 = np.where(u10.diff(50) < 0, np.sign(c.diff(50)), -np.sign(c.diff(50))) * vol_adj
    stop_m3 = ((b3 > 0) & (c < c.rolling(20).min().shift(1))) | ((b3 < 0) & (c > c.rolling(20).max().shift(1)))
    s10_3 = (-np.tanh(z_rr3).ewm(span=6).mean() + np.where(stop_m3, 0, b3)) / 2

    s10_4 = (-zscore(u10.diff(), 10).clip(-1, 1) + np.where((u10 - u10.ewm(span=55).mean()) < 0, np.sign(c.diff(50)), np.where((u10 - u10.ewm(span=55).mean()) > 0, -np.sign(c.diff(50)), 0)) * vol_adj) / 2

    signals.update({
        'U10_RSI_Div_Long':    pd.Series(s10_2, index=c.index).clip(-1, 1).shift(1).fillna(0),
        'U10_RealRates_Blend': pd.Series(s10_3, index=c.index).clip(-1, 1).shift(1).fillna(0),
        'U10_YieldMom_Blend':  pd.Series(s10_4, index=c.index).clip(-1, 1).shift(1).fillna(0)
    })

    # -- US2Y --
    z10 = zscore(u2.diff(), 10)
    su2_1 = np.where(z10 > (1.75 + (u2 > u2.rolling(200).mean()) * 0.5), -1, np.where(z10 < -1.75, 1, 0))

    su2_2 = np.clip(-10 * (u2.pct_change() + (u2.pct_change() - u2.pct_change().shift(1))).ewm(span=3).mean(), -1, 1)

    r_skew = (c / u2).diff().rolling(21).skew()
    su2_3 = np.where(r_skew > 1.0, np.clip(zscore(c / u2, 10), -1, 1), 0)

    up2 = (u2.diff() > 0).astype(int); dn2 = (u2.diff() < 0).astype(int)
    strk_up = up2.groupby((up2 == 0).cumsum()).cumsum()
    strk_dn = dn2.groupby((dn2 == 0).cumsum()).cumsum()
    su2_4 = np.where(u2 < 1.0, np.where(strk_up >= 2, -1, np.where(strk_dn >= 2, 1, 0)), 0)

    b63 = ret.rolling(63).cov(u2.pct_change()) / u2.pct_change().rolling(63).var()
    su2_5 = np.where(np.abs(zscore(u2.diff(), 14)) > 1.5, -np.sign(zscore(u2.diff(), 14)), np.where(b63 > 0, np.sign(c.diff(63)), -np.sign(u2.diff(63))))

    signals.update({
        'U2_YieldRev_Asym':    pd.Series(su2_1, index=c.index).shift(1).fillna(0),
        'U2_ContYield_ZLEMA':  pd.Series(su2_2, index=c.index).shift(1).fillna(0),
        'U2_RatioTrend_Skew':  pd.Series(su2_3, index=c.index).shift(1).fillna(0),
        'U2_YieldStreak_ZIRP': pd.Series(su2_4, index=c.index).shift(1).fillna(0),
        'U2_BetaRegime_OR':    pd.Series(su2_5, index=c.index).shift(1).fillna(0)
    })

