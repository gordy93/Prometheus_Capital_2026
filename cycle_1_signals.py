def build_breadth_base_signals(df):
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)

    up = (ret > 0).astype(int)
    upvol = up * v
    intra_up = (c > o).astype(int)
    dow = df.index.dayofweek
    rsi14 = calc_rsi(c, 14)

    ibm_raw = np.tanh((intra_up.rolling(3).mean() - intra_up.rolling(15).mean()) * 10)
    sig_1 = np.where(c < c.rolling(5).max() * 0.98, 0, np.where(ibm_raw > 0, ibm_raw, 0))

    ud10 = up.rolling(10).mean()
    sig_2 = ((ud10.rolling(10).min() <= 0.2) & (ud10 >= 0.8)).astype(int).shift(1).replace(0, np.nan).ffill(limit=10).fillna(0)

    mas = [c.rolling(w).mean() for w in[5, 10, 20, 50, 100, 200]]
    ma_align = sum((c > ma).astype(int) for ma in mas) / 6.0
    maam_raw = np.tanh((ma_align.rolling(3).mean() - ma_align.rolling(20).mean()) * 10)
    maam_long = np.where(maam_raw > 0, maam_raw, 0)
    sig_3 = np.where(dow == 4, -maam_long, maam_long)

    vol_ud20 = upvol.rolling(20).sum() / (v.rolling(20).sum() + 1e-8)
    z_vwudr = (vol_ud20 - vol_ud20.rolling(252).mean()) / (vol_ud20.rolling(252).std() + 1e-8)
    vwudr_raw = -np.tanh(z_vwudr)
    vol_regime = vol20 / (ret.rolling(100).std() * np.sqrt(252) + 1e-8)
    sig_4 = np.where(vol_regime > 1.2, np.where(vwudr_raw > 0, vwudr_raw, 0), 0)

    stbr_raw = -(up.rolling(2).mean() - 0.5) * 2
    sig_5 = np.where((dow == 4) | (rsi14 > 80) | (rsi14 < 20), 0, stbr_raw)

    return {
        "BrB_01_Intraday_Mom":   pd.Series(sig_1, index=c.index).shift(1).fillna(0),
        "BrB_02_Thrust_BTI":     pd.Series(sig_2, index=c.index).shift(1).fillna(0),
        "BrB_03_MA_Align_Mom":   pd.Series(sig_3, index=c.index).shift(1).fillna(0),
        "BrB_04_VolWeight_Rev":  pd.Series(sig_4, index=c.index).shift(1).fillna(0),
        "BrB_05_ShortTerm_Rev":  pd.Series(sig_5, index=c.index).shift(1).fillna(0)}

