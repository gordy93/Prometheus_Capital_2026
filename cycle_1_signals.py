def build_autocorrelation_signals(df):
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)

    ma_200 = c.rolling(200).mean()
    z_5 = (ret - ret.rolling(5).mean()) / (ret.rolling(5).std() + 1e-6)
    vol_pct = vol20.rolling(252).rank(pct=True)
    gap = o / c.shift(1) - 1

    macd = c.ewm(span=12).mean() - c.ewm(span=26).mean()
    macd_sig = macd.ewm(span=9).mean()
    wick = (c - l) / (h - l + 1e-6)

    sign_ret = np.sign(ret)
    sign_change = sign_ret != sign_ret.shift(1)
    run_len_abs = sign_ret.groupby(sign_change.cumsum()).cumcount() + 1
    run_length = run_len_abs * sign_ret

    sig_1_base = pd.Series(np.where((c > ma_200) & (ret < 0), -z_5, 0), index=c.index).clip(0, 1)
    sig_1_base = sig_1_base * np.where(vol20 < vol20.shift(5), 1, 0)
    sig_1 = (0.5 * sig_1_base + 0.25 * sig_1_base.shift(1).fillna(0) + 0.125 * sig_1_base.shift(2).fillna(0))

    sig_2_base = pd.Series(np.where((c > ma_200) & (ret < 0), 1, 0), index=c.index)
    sig_2_base = sig_2_base * np.where(vol20 < vol20.shift(5), 1, 0)
    sig_2 = np.where(gap > 0, sig_2_base.clip(-1, 0.5), sig_2_base)

    med_vol = vol20.rolling(252).median()
    sig_3_base = pd.Series(np.where(vol20 > med_vol, -np.sign(ret), np.sign(ret)), index=c.index)
    sig_3_base = (sig_3_base + sig_3_base.shift(1).fillna(0) + sig_3_base.shift(2).fillna(0)) / 3
    sig_3 = sig_3_base * np.where(c.ewm(span=50).mean() > c.ewm(span=200).mean(), 1, 0)

    sig_4_base = pd.Series(np.where((vol_pct > 0.5) & (ret < 0), 1, 0), index=c.index)
    sig_4_base = sig_4_base * np.where(np.sign(gap) != np.sign(sig_4_base), 1, 0)
    sig_4 = sig_4_base.ewm(span=5).mean()

    sigA = np.where((vol_pct > 0.5) & (vol_pct <= 0.75) & (ret < 0), 1, 0)
    sigB = np.where((vol_pct > 0.75) & (run_length >= 2), -1, 0)
    sigC = np.where((vol_pct <= 0.5), np.sign(ret), 0)
    sig_5_base = pd.Series(sigA + sigB + sigC, index=c.index).clip(-1, 1)
    sig_5_base = sig_5_base * np.where(wick > 0.5, 1, 0)
    sig_5 = sig_5_base.ewm(span=5).mean()

    vol_ma = v.rolling(20).mean()
    sig_6_base = pd.Series(np.where((ret < 0) & (v <= vol_ma), 1, 0), index=c.index)
    sig_6 = sig_6_base.ewm(span=5).mean()

    streak = (ret < 0) & (ret.shift(1) < 0) & (ret.shift(2) < 0)
    sig_7_base = pd.Series(np.where((c > ma_200) & streak & (macd > macd_sig), 1, 0), index=c.index)
    ac = ret.rolling(20).corr(ret.shift(1))
    sig_7 = sig_7_base * np.where(ac.diff() > 0, 1, 0)

    return {
        "ACor_01_UpTrend_DipScale_Dyn": pd.Series(sig_1, index=c.index).shift(1).fillna(0),
        "ACor_02_UpTrend_DipBuy_Gap":   pd.Series(sig_2, index=c.index).shift(1).fillna(0),
        "ACor_03_VolCond_EMA_Cross":    pd.Series(sig_3, index=c.index).shift(1).fillna(0),
        "ACor_04_HighVol_DipBuy_EMA5":  pd.Series(sig_4, index=c.index).shift(1).fillna(0),
        "ACor_05_Ensemble_Wick_EMA5":   pd.Series(sig_5, index=c.index).shift(1).fillna(0),
        "ACor_06_AsymRev_VolDry_EMA5":  pd.Series(sig_6, index=c.index).shift(1).fillna(0),
        "ACor_07_UpTrend_Dn3_MACD":     pd.Series(sig_7, index=c.index).shift(1).fillna(0)}

