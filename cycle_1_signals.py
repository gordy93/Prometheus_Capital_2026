def build_rates_fx_signals(df):
    if "Close_US10Y" not in df.columns: return {}
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)

    u10 = df["Close_US10Y"]
    u2 = df["Close_US2Y"]
    eur = df["Close_EUR"]
    uj = df["Close_UJ"]

    # US10Y
    rsi_diff = calc_rsi(c, 9) - calc_rsi(u10, 9)
    sig_1 = np.where(vol20 < vol20.rolling(277).median(), np.tanh(zscore(rsi_diff, 55)), 0).clip(0, 1)

    z_rr3 = zscore(c * u10, 11)
    b3 = np.where(u10.diff(50) < 0, np.sign(c.diff(50)), -np.sign(c.diff(50))) * vol_adj
    stop_m3 = ((b3 > 0) & (c < c.rolling(20).min().shift(1))) | ((b3 < 0) & (c > c.rolling(20).max().shift(1)))
    sig_2 = (-np.tanh(z_rr3).ewm(span=6).mean() + np.where(stop_m3, 0, b3)) / 2

    sig_3 = (-zscore(u10.diff(), 10).clip(-1, 1) + np.where((u10 - u10.ewm(span=55).mean()) < 0, np.sign(c.diff(50)), np.where((u10 - u10.ewm(span=55).mean()) > 0, -np.sign(c.diff(50)), 0)) * vol_adj) / 2

    # US2Y
    z10 = zscore(u2.diff(), 10)
    sig_4 = np.where(z10 > (1.75 + (u2 > u2.rolling(200).mean()) * 0.5), -1, np.where(z10 < -1.75, 1, 0))

    sig_5 = np.clip(-10 * (u2.pct_change() + (u2.pct_change() - u2.pct_change().shift(1))).ewm(span=3).mean(), -1, 1)

    r_skew = (c / u2).diff().rolling(21).skew()
    sig_6 = np.where(r_skew > 1.0, np.clip(zscore(c / u2, 10), -1, 1), 0)

    up2 = (u2.diff() > 0).astype(int)
    dn2 = (u2.diff() < 0).astype(int)
    strk_up = up2.groupby((up2 == 0).cumsum()).cumsum()
    strk_dn = dn2.groupby((dn2 == 0).cumsum()).cumsum()
    sig_7 = np.where(u2 < 1.0, np.where(strk_up >= 2, -1, np.where(strk_dn >= 2, 1, 0)), 0)

    b63 = ret.rolling(63).cov(u2.pct_change()) / u2.pct_change().rolling(63).var()
    sig_8 = np.where(np.abs(zscore(u2.diff(), 14)) > 1.5, -np.sign(zscore(u2.diff(), 14)), np.where(b63 > 0, np.sign(c.diff(63)), -np.sign(u2.diff(63))))

    # EUR/USD
    c50 = ret.rolling(50).corr(eur.pct_change())
    e_mom20 = eur.pct_change(20).abs()
    g_mom20 = c.pct_change(20).abs()
    atr14 = tr.rolling(14).mean()

    sig_9 = np.clip(np.where(c50 > 0, 1, np.where(c.pct_change(40) < 0.02, -1, 0)) * (e_mom20 / e_mom20.median()), -1, 1) * (atr14.median() / atr14)

    sig_10 = np.where(vol20 > vol20.median(), np.clip(np.where(c50 > 0, 1, np.where(c.pct_change(40) < 0, -1, 0)) * (g_mom20 / g_mom20.median()), -1, 1) * 0.5, np.clip(np.where(c50 > 0, 1, np.where(c.pct_change(40) < 0, -1, 0)) * (g_mom20 / g_mom20.median()), -1, 1))

