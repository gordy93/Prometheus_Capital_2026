class LongTermTrendSignals(BaseSignalFamily):
    def generate_signals(self):
        df = self.df
        df['Ret'] = df['Close'].pct_change()

        def lin_reg_score(y):
            x = np.arange(len(y))
            var_x = ((x - x.mean())**2).sum()
            if var_x == 0: return 0
            cov = ((x - x.mean()) * (y - y.mean())).sum()
            var_y = ((y - y.mean())**2).sum()
            if var_y == 0: return 0
            r = cov / np.sqrt(var_x * var_y + 1e-8)
            return r * np.sign(cov / var_x)

        vol60 = df['Ret'].rolling(60).std() * np.sqrt(252)
        vol54 = df['Ret'].rolling(54).std() * np.sqrt(252)
        vol66 = df['Ret'].rolling(66).std() * np.sqrt(252)
        vol252 = df['Ret'].rolling(252).std() * np.sqrt(252)
        skew252 = df['Ret'].rolling(252).skew()

        vol_scale = np.clip(0.15 / (vol60 + 1e-4), 0.2, 2.0)
        v_scale_m10 = np.clip(0.15 / (vol54 + 1e-4), 0.2, 2.0)
        v_scale_p10 = np.clip(0.15 / (vol66 + 1e-4), 0.2, 2.0)

        mom_120 = df['Close'].pct_change(120) / (vol252 + 1e-4)
        mom_252 = df['Close'].pct_change(252) / (vol252 + 1e-4)
        Dual_Mom = np.clip(((np.tanh(mom_120 * 2) + np.tanh(mom_252 * 2)) / 2) * vol_scale, -1, 1)

        rs_180 = df['Close'].rolling(180).apply(lin_reg_score, raw=True)
        sig_lr_180 = np.clip(rs_180 * v_scale_m10 * 2, -1, 1)
        rs_200 = df['Close'].rolling(200).apply(lin_reg_score, raw=True)
        LinReg_200 = pd.Series(np.clip(rs_200 * vol_scale * 2, -1, 1), index=df.index)
        rs_220 = df['Close'].rolling(220).apply(lin_reg_score, raw=True)
        sig_lr_220 = np.clip(rs_220 * v_scale_p10 * 2, -1, 1)

        rib_180 = sum(np.where(df['Close'] > df['Close'].rolling(i).mean(), 1, -0.2) for i in range(45, 185, 9)) / 16
        sig_rib_180 = pd.Series(np.clip(rib_180 * v_scale_m10, -1, 1), index=df.index)
        rib_200 = sum(np.where(df['Close'] > df['Close'].rolling(i).mean(), 1, -0.2) for i in range(50, 210, 10)) / 16
        sig_rib_200 = pd.Series(np.clip(rib_200 * vol_scale, -1, 1), index=df.index)
        rib_220 = sum(np.where(df['Close'] > df['Close'].rolling(i).mean(), 1, -0.2) for i in range(55, 225, 11)) / 16
        sig_rib_220 = pd.Series(np.clip(rib_220 * v_scale_p10, -1, 1), index=df.index)

        Blend_m10 = (sig_lr_180 + sig_rib_180) / 2
        Blend_p10 = (sig_lr_220 + sig_rib_220) / 2

        min252 = df['Close'].rolling(252).min()
        max252 = df['Close'].rolling(252).max()
        donch = 2 * ((df['Close'] - min252) / (max252 - min252 + 1e-4)) - 1
        Smooth_Donchian = np.clip(donch.ewm(span=50).mean() * vol_scale, -1, 1)

        dist200 = df['Close'] / df['Close'].rolling(200).mean() - 1
        dist200_z = dist200 / (dist200.rolling(252).std() + 1e-4)
        z_dist_200ma = np.clip(np.tanh(dist200_z) * vol_scale, -1, 1)
        Asym_ZDist = pd.Series(np.where(z_dist_200ma > 0, z_dist_200ma, z_dist_200ma * 0.5), index=df.index)

        Blend_Top5 = (LinReg_200 + sig_rib_200 + Smooth_Donchian + Asym_ZDist + Dual_Mom) / 5

        L2_Dual_Mom_Cube = Dual_Mom ** 3
        L2_Blend_LinReg_Rib_m10_DoW = np.where(df.index.dayofweek == 4, Blend_m10 * 0.8, Blend_m10)
        L2_Blend_LinReg_Rib_p10_Squash = np.sign(Blend_p10) * np.sqrt(np.abs(Blend_p10))
        L2_Blend_Top5_Cube = Blend_Top5 ** 3

        er20 = df['Close'].diff(20).abs() / (df['Close'].diff().abs().rolling(20).sum() + 1e-8)
        L2_LinReg_200_ER_Boost = LinReg_200 * np.where(er20 > 0.3, 1.2, 0.8)

        def apply_softmax(b): return np.sign(b) * (np.exp(np.abs(b)*5) - 1) / (np.exp(5) - 1)
        def apply_tow_fade(b): return np.where((df.index.dayofweek == 1) & (df['Ret'].shift(1) > 0.01), b * 0.5, b)
        def apply_skew(b): return b * np.where(skew252 > 0, 1.1, 0.9)
        def apply_asym_exp(b): return np.where(b > 0, b**3, b**5)

        self.signals['L2_Dual_Mom_Cube_Softmax'] = np.clip(apply_softmax(L2_Dual_Mom_Cube), -1, 1)
        self.signals['L2_Blend_LinReg_Rib_m10_DoW_TOWFade'] = np.clip(apply_tow_fade(L2_Blend_LinReg_Rib_m10_DoW), -1, 1)
        self.signals['L2_LinReg_200_ER_Boost_Softmax'] = np.clip(apply_softmax(L2_LinReg_200_ER_Boost), -1, 1)
        self.signals['L2_Blend_LinReg_Rib_p10_Squash_TOWFade'] = np.clip(apply_tow_fade(L2_Blend_LinReg_Rib_p10_Squash), -1, 1)
        self.signals['L2_Blend_LinReg_Rib_m10_DoW_Skew'] = np.clip(apply_skew(L2_Blend_LinReg_Rib_m10_DoW), -1, 1)
        self.signals['L2_Blend_LinReg_Rib_p10_Squash_Skew'] = np.clip(apply_skew(L2_Blend_LinReg_Rib_p10_Squash), -1, 1)
        self.signals['L2_LinReg_200_ER_Boost_AsymExp'] = np.clip(apply_asym_exp(L2_LinReg_200_ER_Boost), -1, 1)
        self.signals['L2_Blend_Top5_Cube_Softmax'] = np.clip(apply_softmax(L2_Blend_Top5_Cube), -1, 1)
        self.signals['L2_LinReg_200_ER_Boost_Skew'] = np.clip(apply_skew(L2_LinReg_200_ER_Boost), -1, 1)
        self.signals['L2_LinReg_200_ER_Boost_TOWFade'] = np.clip(apply_tow_fade(L2_LinReg_200_ER_Boost), -1, 1)


class MediumTermTrendSignals(BaseSignalFamily):
    def generate_signals(self):
        c, h, l, v = self.df['Close'], self.df['High'], self.df['Low'], self.df['Volume']
        ret = c.pct_change()
        self.df['Ret'] = ret

        vol20 = ret.rolling(20).std() * np.sqrt(252)
        vol60 = ret.rolling(60).std() * np.sqrt(252)
        vol120 = ret.rolling(120).std() * np.sqrt(252)
        vol_of_vol_20 = ret.rolling(20).std().rolling(20).std()

        tr = pd.DataFrame({'hl': h-l, 'hc': (h-c.shift()).abs(), 'lc': (l-c.shift()).abs()}).max(axis=1)
        drawdown_14 = (c - c.rolling(14).max()) / c.rolling(14).max()
        ulcer_14 = np.sqrt((drawdown_14**2).rolling(14).mean()) * 100

        macd = c.ewm(span=12).mean() - c.ewm(span=26).mean()
        macd_hist = macd - macd.ewm(span=9).mean()

        autocorr20 = ret.rolling(20).apply(lambda x: pd.Series(x).autocorr(1) if len(x)>5 else 0, raw=True)
        kurt20 = ret.rolling(20).kurt()

        def calc_density(w): return (h.rolling(w).max() - l.rolling(w).min()) / (tr.rolling(w).sum() + 1e-5)
        def scale_final(s):
            s_std = s.rolling(252, min_periods=40).std().replace(0, np.nan).ffill().bfill()
            return np.tanh(s / s_std).fillna(0)

        raw1 = c.shift(27).pct_change(27) - c.pct_change(27)
        sig1 = raw1 * (ret.rolling(20).std() > ret.rolling(60).std()).astype(float)
        self.signals['Trend_Decel_55_VolBreakout_VolOfVol'] = scale_final(sig1 / (vol_of_vol_20 + 1e-5))

        raw2 = c.shift(30).pct_change(30) - c.pct_change(30)
        self.signals['Trend_Decel_60_VolBreakout_LongOnly'] = scale_final(raw2 * (vol20 > vol60).astype(float)).clip(0, 1)

        raw3 = -np.sign(c.pct_change(40)) * -c.pct_change(10)
        scaled3 = scale_final(np.sign(raw3) * (np.abs(raw3)**2))
        self.signals['Trend_Breakdown_40_SignPower_Lagged'] = 0.7 * scaled3 + 0.3 * scaled3.shift(5).fillna(0)

        raw4 = c.pct_change(25) * (1 - (ret.rolling(25).std()*np.sqrt(252) / vol120))
        self.signals['LowVol_Trend_25_SigMom_LongOnly'] = scale_final(raw4 + raw4.diff(3).fillna(0)).clip(0, 1)

        raw5 = pd.Series(np.where(ret.rolling(55).std()*np.sqrt(252) < vol120, c.pct_change(55), 0), index=c.index)
        self.signals['Consol_Breakout_55_MACDAlign_Ulcer'] = scale_final((raw5 * (np.sign(raw5) == np.sign(macd_hist)).astype(float)) / (ulcer_14 + 1))

        raw6 = -np.sign(c.pct_change(55)) * -c.pct_change(13)
        self.signals['Trend_Breakdown_55_EMASmooth_AutoCorr'] = scale_final(raw6.ewm(span=3).mean() * np.where(autocorr20 < 0, 0.5, 1.2))

        raw7 = -np.sign(c.pct_change(50)) * -c.pct_change(12)
        dens7 = calc_density(20)
        self.signals['Trend_Breakdown_50_KurtFilter_PriceDens'] = scale_final((raw7 * (kurt20 < 5.0).astype(float)) * (dens7 > dens7.rolling(252).median()).astype(float))

        raw8 = -np.sign(c.pct_change(35)) * -c.pct_change(8)
        self.signals['Trend_Breakdown_35_MedianFilter_LongBias'] = scale_final(raw8.rolling(3).median()) + 0.2

        raw9 = pd.Series(np.where(vol20 < vol120, c.pct_change(20), 0), index=c.index)
        self.signals['Consol_Breakout_20_MACDAlign_LongBias'] = scale_final(raw9 * (np.sign(raw9) == np.sign(macd_hist)).astype(float)) + 0.2


class ShortTermTrendSignals(BaseSignalFamily):
    def generate_signals(self):
        df = self.df
        df['Return'] = df['Close'].pct_change()
        ret1 = df['Return']

        ret2 = df['Close'].pct_change(2)
        ret5 = df['Close'].pct_change(5)
        ret10 = df['Close'].pct_change(10)
        ret20 = df['Close'].pct_change(20)

        vol20 = df['Return'].rolling(20).std() * np.sqrt(252)
        scaler = (0.15 / (vol20 + 1e-6)).clip(0, 2.0)

        z10 = (df['Close'] - df['Close'].rolling(10).mean()) / (df['Close'].rolling(10).std() + 1e-6)
        accel = ret5 - ret20
        macd = df['Close'].ewm(span=5).mean() - df['Close'].ewm(span=10).mean()

        obv = (np.sign(df['Return']) * df['Volume']).rolling(10).sum()
        gap_pct = df['Open'] / df['Close'].shift(1) - 1
        gap_down = df['Open'] < df['Low'].shift(1)
        roll_skew = df['Return'].rolling(60).skew()
        roll_kurt = df['Return'].rolling(60).kurt()
        down_dev = df['Return'].clip(upper=0).rolling(60).std()
        up_dev = df['Return'].clip(lower=0).rolling(60).std()
        high_vol_regime = vol20 > vol20.rolling(252).median()

        up = df['Return'].clip(lower=0)
        dn = -1 * df['Return'].clip(upper=0)
        rsi14 = 100 - (100 / (1 + up.ewm(com=13).mean() / (dn.ewm(com=13).mean() + 1e-6)))

        def linreg_r2(x):
            n = len(x)
            return scipy.stats.linregress(np.arange(n), x)[2]**2 if n >= 3 else 0
        r2_10 = df['Close'].rolling(10).apply(linreg_r2).fillna(0)

        z_sym = np.where((z10 > 0) & (z10 < 1.0) & (ret1 < 0), 1, np.where((z10 < 0) & (z10 > -1.0) & (ret1 > 0), -1, 0)) * scaler
        z_asym = np.where((z10 > 0) & (z10 < 1.0) & (ret1 < 0), 1, np.where((z10 < 0) & (z10 > -1.0) & (ret1 > 0), -0.5, 0)) * scaler
        t_sym = np.where((ret10 > 0) & (ret2 < 0), 1, np.where((ret10 < 0) & (ret2 > 0), -1, 0)) * scaler
        t_asym = np.where((ret10 > 0) & (ret2 < 0), 1, np.where((ret10 < 0) & (ret2 > 0), -0.5, 0)) * scaler
        a_pb = np.where((accel > 0) & (ret1 < 0), 1, np.where((accel < 0) & (ret1 > 0), -1, 0)) * scaler
        z_long = np.where((z10 > 0) & (z10 < 1.0) & (ret1 < 0), 1, 0) * scaler
        macd_pb = np.where((macd > 0) & (ret2 < 0), 1, np.where((macd < 0) & (ret2 > 0), -1, 0)) * scaler
        z_cont = np.where((z10 > 0) & (z10 < 1.0) & (ret1 < 0), 1 - 2*np.abs(z10 - 0.5), np.where((z10 < 0) & (z10 > -1.0) & (ret1 > 0), -1 + 2*np.abs(z10 + 0.5), 0)) * scaler

        self.signals['Composite_Z10_Trend10_GapDown_ConvictionScale'] = np.where(gap_down, np.clip(z_sym + t_sym, -1, 1), 0) * r2_10
        self.signals['Trend10_PB2_GapDown_ConvictionScale'] = np.where(gap_down, t_sym, 0) * r2_10
        self.signals['Trend10_PB2_Asym_GapDown_ConvictionScale'] = np.where(gap_down, t_asym, 0) * r2_10
        self.signals['Z10_PB_LongOnly_Distribution_LowSkew'] = np.where(roll_skew < 0, np.where(obv < 0, z_long, 0), 0)
        self.signals['MACD_PB_GapDown_LowKurtosis'] = np.where(roll_kurt < 3, np.where(gap_down, macd_pb, 0), 0)
        self.signals['Smart_Trend_Alpha_RSINeutral_GapDownMicro'] = np.where((gap_pct < 0) & (gap_pct > -0.005), np.where((rsi14 >= 30) & (rsi14 <= 70), np.clip(z_asym + t_asym + a_pb, -1, 1), 0), 0)
        self.signals['Z10_PB_Continuous_GapDown_DownsideDevHigh'] = np.where(down_dev > up_dev, np.where(gap_down, z_cont, 0), 0)
        self.signals['Trend_Accel_PB_HighVolRegime_GapDownMicro'] = np.where((gap_pct < 0) & (gap_pct > -0.005), np.where(high_vol_regime, a_pb, 0), 0)


class VolumeSignals(BaseSignalFamily):
    def generate_signals(self):
        df = self.df
        df['Ret'] = df['Close'].pct_change()
        df['H_L'] = df['High'] - df['Low']
        df['TR'] = np.maximum(df['H_L'], np.maximum(abs(df['High'] - df['Close'].shift()), abs(df['Low'] - df['Close'].shift())))
        df['Ann_Vol'] = df['Ret'].rolling(20).std() * np.sqrt(252)

        def scale_cap(sig, target_vol=0.15):
            inv_vol = target_vol / df['Ann_Vol'].replace(0, np.nan)
            return (sig * inv_vol.fillna(1).clip(0.1, 2.0)).clip(-1, 1)

        ivi = ((2*df['Close'] - df['High'] - df['Low']) / df['H_L'].replace(0, np.nan)) * df['Volume']
        hv_s = df['Ret'].rolling(10).std()
        hv_l = df['Ret'].rolling(100).std()
        atr = df['TR'].rolling(14).mean()
        vwap = (df['Close'] * df['Volume']).rolling(10).sum() / df['Volume'].rolling(10).sum()
        mfv = ((df['Close'] - df['Low']) - (df['High'] - df['Close'])) / df['H_L'].replace(0, np.nan) * df['Volume']
        chop = 100 * np.log10(df['TR'].rolling(14).sum() / (df['High'].rolling(14).max() - df['Low'].rolling(14).min())) / np.log10(14)
        vpt = (df['Ret'] * df['Volume']).cumsum()
        vma = df['Volume'].rolling(20).mean()

        sig2 = np.sign(ivi.rolling(40).mean())
        sig2 = np.where(df['Ret'].rolling(5).sum() > 0.02, 0, sig2)
        self.signals['S2_IVI'] = scale_cap(pd.Series(np.where(hv_s < hv_l, sig2, sig2 * 0.5), index=df.index))

        sig3 = np.sign(vpt.rolling(10).mean() - vpt.rolling(55).mean())
        sig3 = np.where(df['TR'] > atr, sig3, sig3 * 0.5)
        self.signals['S3_VPT'] = scale_cap(pd.Series(np.where((df['Close'] > vwap) & (sig3 < 0), 0, sig3), index=df.index))

        cmf40 = mfv.rolling(40).sum() / df['Volume'].rolling(40).sum()
        sig4 = np.tanh(cmf40 * 5)
        sig4 = np.where(df['TR'] > atr, sig4, sig4 * 0.5)
        self.signals['S4_CMF40'] = scale_cap(pd.Series(np.where(chop > 61.0, sig4, sig4 * 0.5), index=df.index))

        vw1 = (df['Close'] * df['Volume']).rolling(10).sum() / df['Volume'].rolling(10).sum()
        vw2 = (df['Close'] * df['Volume']).rolling(50).sum() / df['Volume'].rolling(50).sum()
        sig5 = np.sign(vw1 - vw2)
        sig5 = np.where(df['TR'] > atr, sig5, sig5 * 0.5)
        self.signals['S5_VWAP'] = scale_cap(pd.Series(np.where(chop > 61.0, sig5, sig5 * 0.5), index=df.index))

        sig6 = np.sign(ivi.rolling(50).mean())
        sig6 = np.where(df['TR'] > atr, sig6, sig6 * 0.5)
