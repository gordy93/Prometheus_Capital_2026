class MarketEfficiencyNoiseSignals(BaseSignalFamily):
    def generate_signals(self):
        df = self.df
        c, o, v = df['Close'], df['Open'], df['Volume']
        ret = c.pct_change()
        df['Ret'] = ret

        def get_er(c_s, lag):
            return (c_s.diff(lag).abs() / c_s.diff().abs().rolling(lag).sum()).fillna(0)
        def get_ac(ret_s, lag):
            return ret_s.rolling(lag).apply(lambda x: pd.Series(x).autocorr(lag=1) if len(x)>1 else np.nan).fillna(0)

        # 1. Vol_Regime_UpTrend
        er = get_er(c, 10)
        vol_ma = v.rolling(20).mean()
        ma = c.rolling(200).mean()
        body = c - o
        S_raw = np.where(er > 0.3, ((v / vol_ma - 1).clip(0, 3)) * np.sign(ret), -((v / vol_ma - 1).clip(0, 3)) * np.sign(ret))
        base1 = np.where(np.sign(body) == np.sign(S_raw), S_raw, 0)
        self.signals['Vol_Regime_UpTrend'] = np.where(c > ma, np.where(base1 > 0, base1, 0), base1)

        # 2. Vol_Regime_Rev_UpTrend
        v_sh = ret.rolling(20).std()
        v_lg = ret.rolling(100).std()
        base2 = np.where(v > vol_ma, np.where(v_sh > v_lg, -np.sign(ret), np.sign(ret)), 0)
        self.signals['Vol_Regime_Rev_UpTrend'] = np.where(c > ma, np.where(base2 > 0, base2, 0), base2)

        # 3. ER_Breakout_Drift
        ac = get_ac(ret, 10)
        drift = (o - c.shift(1)).rolling(5).sum()
        bk_up = c > c.rolling(20).max().shift(1)
        bk_dn = c < c.rolling(20).min().shift(1)
        base3 = np.where(ac > 0.1, np.where(bk_up & (er > 0.3), 1, np.where(bk_dn & (er > 0.3), -1, 0)), 0)
        self.signals['ER_Breakout_Drift'] = np.where(np.sign(drift) == np.sign(base3), base3, 0)


class AutocorrelationSignals(BaseSignalFamily):
    def generate_signals(self):
        df = self.df
        df['Ret1'] = df['Close'].pct_change()
        df['Ret'] = df['Ret1']

        df['Vol20'] = df['Ret1'].rolling(20).std()
        df['MA50'] = df['Close'].rolling(50).mean()
        df['MA200'] = df['Close'].rolling(200).mean()
        df['SqRet'] = df['Ret1']**2
        df['SqRet_EMA20'] = df['SqRet'].ewm(span=20).mean()
        df['InsideDay'] = (df['High'] < df['High'].shift(1)) & (df['Low'] > df['Low'].shift(1))
        df['Ret5'] = df['Close'].pct_change(5)

        dir_20 = df['Close'].diff(20).abs()
        vol_sum_20 = df['Close'].diff().abs().rolling(20).sum()
        df['ER20'] = dir_20 / (vol_sum_20 + 1e-8)

        # 1. Contrarian Trap-Door
        self.signals['Contrarian_Trap_Door'] = (np.where(df['Ret1'] < 0, df['Ret1'].abs() / df['Vol20'], 0)) * \
                 (np.where(df['Close'] <= df['MA200'], 1, 0)) * \
                 (np.where(df['SqRet'] > df['SqRet_EMA20'], 1, 0))

        # 2. Efficient Pullback
        trend_cond = np.where((df['MA50'] > df['MA200']) & (df['Ret1'] < 0), 1, np.where((df['MA50'] < df['MA200']) & (df['Ret1'] > 0), -1, 0))
        self.signals['Efficient_Pullback'] = trend_cond * (np.where(df['Ret5'] <= 0, 1, 0)) * (np.where(df['ER20'] > 0.3, 1, 0))

        # 3. Silent Breakout
        self.signals['Silent_Breakout'] = (df['Ret1'].shift(1).fillna(0)) * (np.where(df['InsideDay'], 1, 0)) * (np.where(df['SqRet'] <= df['SqRet_EMA20'], 1, 0))


class ReturnCorrelationSignals(BaseSignalFamily):
    def generate_signals(self):
        df = self.df
        df['Ret'] = df['Close'].pct_change()
        df['ID_Ret'] = df['Close'] / df['Open'] - 1

        w, pct, cap, smooth = 40, 0.7, 0.022, 6
        ret_sum = df['Ret'].rolling(w).sum()
        id_sum = df['ID_Ret'].rolling(w).sum()
        ret_max = df['Ret'].rolling(w).max()
        base_cond_s8 = (ret_sum > 0) & (id_sum > pct * ret_sum) & (ret_max < cap)

        macd = df['Close'].ewm(span=12).mean() - df['Close'].ewm(span=26).mean()
        macd_bull = macd > macd.ewm(span=9).mean()
        inverse_vol = np.clip(0.10 / (df['Ret'].rolling(20).std() * np.sqrt(252) + 1e-5), 0, 1.5)
        self.signals['S8_MACD_Bull_Inverse_Vol'] = (base_cond_s8 & macd_bull).astype(float).rolling(smooth).mean() * inverse_vol

        base_cond_s2 = (ret_sum > 0) & (id_sum > 1.0 * ret_sum) & (ret_max < cap)
        rs = df['Close'].diff().where(df['Close'].diff() > 0, 0).rolling(14).mean() / (-df['Close'].diff().where(df['Close'].diff() < 0, 0).rolling(14).mean() + 1e-8)
        rsi_gt_40 = (100 - (100 / (1 + rs))) > 40
        donchian_bull = df['Close'] > (df['High'].rolling(20).max() + df['Low'].rolling(20).min()) / 2
        cmf = (((df['Close'] - df['Low']) - (df['High'] - df['Close'])) / (df['High'] - df['Low'] + 1e-5)) * df['Volume']
        cmf_bull = (cmf.rolling(20).sum() > 0).astype(float)
        self.signals['S2_Filter_CMF_Bull'] = (base_cond_s2 & rsi_gt_40).astype(float).rolling(smooth).mean() * donchian_bull.astype(float) * cmf_bull

        ud_vol_bull = (df['Volume'] * (df['Ret'] > 0)).rolling(50).sum() / ((df['Volume'] * (df['Ret'] < 0)).rolling(50).sum() + 1e-8) > 1.0
        tr = np.maximum(df['High'] - df['Low'], np.maximum(abs(df['High'] - df['Close'].shift(1)), abs(df['Low'] - df['Close'].shift(1))))
        inverse_atr = np.clip(0.10 / (tr.rolling(14).mean() / df['Close'] * np.sqrt(252) + 1e-5), 0, 1.5)
        self.signals['S9_Scale_Inverse_ATR'] = (base_cond_s8 & macd_bull).astype(float).rolling(5).mean() * ud_vol_bull.astype(float) * inverse_atr


