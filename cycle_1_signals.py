def build_low_vix_signals(df):
    if 'Close_VIX' not in df.columns: return {}
    o, h, l, c, v, ret, tr, vol20, vol60, vol_adj = compute_base(df)

    vix = df['Close_VIX']
    no_fri = np.where(c.index.dayofweek != 4, 1, 0)

    # S1: Adaptive_Inv_VIX
    s1 = np.clip(vix.rolling(200).mean() / vix, 0, 1) * no_fri

    # S2: Smoothed_Inv_VIX
    s2 = np.clip(vix.rolling(50).mean() / vix, 0, 1) * no_fri

    # S3: Vol_Target_Scaling_VIX200
    s3 = np.clip(0.15 / (vol20 + 1e-8), 0, 1) * np.where(vix < vix.rolling(200).mean(), 1, 0) * no_fri

    # S4: RiskAdj_Momentum
    g_ret = c.pct_change(20)
    v_ret = vix.pct_change(20)
    g_vol = ret.rolling(20).std()
    v_vol = vix.pct_change().rolling(20).std()
    s4 = np.where((g_ret / (g_vol + 1e-5)) > (v_ret / (v_vol + 1e-5)), 1, 0) * no_fri

    # S5: Scaled_VIX_MACD
    ema_short = c.ewm(span=12, adjust=False).mean()
    ema_long = c.ewm(span=26, adjust=False).mean()
    base_scale = np.clip(vix.rolling(50).mean() / vix, 0, 1)
    s5 = np.where(ema_short > ema_long, base_scale, 0) * no_fri

    # S6: VIX_RSI_LT_50
    v_rsi = calc_rsi(vix, 14)
    s6 = np.where(v_rsi < 50, 1, 0) * no_fri

    # S7: VIX_SkewPos_GLD_Uptrend
    v_skew = vix.pct_change().rolling(20).skew()
    g_ma50 = c.rolling(50).mean()
    s7 = np.where((v_skew > 0) & (c > g_ma50), 1, 0) * no_fri

    # S8: VIX_MACD_Bearish
    v_ema_s = vix.ewm(span=12, adjust=False).mean()
    v_ema_l = vix.ewm(span=26, adjust=False).mean()
    v_macd = v_ema_s - v_ema_l
    v_sig = v_macd.ewm(span=9, adjust=False).mean()
    s8 = np.where(v_macd < v_sig, 1, 0) * no_fri

    # S9: VIX_Stoch_LT_50
    low_min = vix.rolling(14).min()
    high_max = vix.rolling(14).max()
    v_k = 100 * (vix - low_min) / (high_max - low_min + 1e-8)
    s9 = np.where(v_k < 50, 1, 0) * no_fri

    # S10: GLD_RSI_GT_VIX_RSI
    g_rsi = calc_rsi(c, 14)
    s10 = np.where(g_rsi > v_rsi, 1, 0) * no_fri

    return {
        'LVIX_Adaptive_Inv_VIX':      pd.Series(s1, index=c.index).shift(1).fillna(0),
        'LVIX_Smoothed_Inv_VIX':      pd.Series(s2, index=c.index).shift(1).fillna(0),
        'LVIX_Vol_Target_Scaling200': pd.Series(s3, index=c.index).shift(1).fillna(0),
        'LVIX_RiskAdj_Momentum':      pd.Series(s4, index=c.index).shift(1).fillna(0),
        'LVIX_Scaled_VIX_MACD':       pd.Series(s5, index=c.index).shift(1).fillna(0),
        'LVIX_VIX_RSI_LT_50':         pd.Series(s6, index=c.index).shift(1).fillna(0),
        'LVIX_VIX_SkewPos_Uptrend':   pd.Series(s7, index=c.index).shift(1).fillna(0),
        'LVIX_VIX_MACD_Bearish':      pd.Series(s8, index=c.index).shift(1).fillna(0),
        'LVIX_VIX_Stoch_LT_50':       pd.Series(s9, index=c.index).shift(1).fillna(0),
        'LVIX_GLD_RSI_GT_VIX_RSI':    pd.Series(s10, index=c.index).shift(1).fillna(0)
    }

