"""### Helper Functions (run once)"""

def strat_ret(sig, mask=None):
    """Daily P&L of a signal (already shifted inside gld_signals)."""
    r = sig * full_df['Ret']
    return r[mask] if mask is not None else r

def metrics(sig, mask=None):
    """Full performance metrics for one signal over a mask."""
    r = strat_ret(sig, mask).fillna(0)
    if len(r) < 10 or r.std() == 0:
        return dict(Sharpe=0, Sortino=0, Calmar=0, TotalRet=0,
                    MaxDD=0, WinRate=0, AvgWin=0, AvgLoss=0,
                    WLRatio=0, LongDays=0, ShortDays=0, FlatDays=0,
                    AvgHold=0, Turnover=0, TimeUnderwater=0,
                    VaR5=0, CVaR5=0, Skew=0, Kurt=0,
                    AnnRet=0, AnnVol=0)

    cum   = (1 + r).cumprod()
    roll_max = cum.cummax()
    dd    = (cum / roll_max) - 1

    ann_ret = r.mean() * 252
    ann_vol = r.std() * np.sqrt(252)
    sharpe  = ann_ret / ann_vol

    downside = r[r < 0]
    sortino  = ann_ret / (downside.std() * np.sqrt(252)) if len(downside) > 0 else 0
    max_dd   = dd.min()
    calmar   = ann_ret / abs(max_dd) if max_dd < 0 else 0

    total_ret = cum.iloc[-1] - 1
    wins   = r[r > 0]
    losses = r[r < 0]
    win_rate = len(wins) / len(r[r != 0]) if len(r[r != 0]) > 0 else 0
    avg_win  = wins.mean()  if len(wins)   > 0 else 0
    avg_loss = losses.mean() if len(losses) > 0 else 0
    wl_ratio = abs(avg_win / avg_loss) if avg_loss != 0 else 0

    # Position stats
    sig_m = sig[mask] if mask is not None else sig
    sig_m = sig_m.astype(float).fillna(0)
    long_d  = (sig_m > 0.05).sum()
    short_d = (sig_m < -0.05).sum()
    flat_d  = ((sig_m >= -0.05) & (sig_m <= 0.05)).sum()

    # Turnover & avg hold
    pos_chg = (sig_m.diff().abs() > 0.05).sum()
    n_days  = len(sig_m)
    turnover = pos_chg / n_days if n_days > 0 else 0

    # Trades = sign changes
    sign = np.sign(sig_m.where(sig_m.abs() > 0.05, 0))
    trades = (sign.diff().abs() > 0).sum()
    avg_hold = (long_d + short_d) / max(trades, 1)

    # Time underwater
    time_uw = (dd < 0).sum() / len(dd) if len(dd) > 0 else 0

    # VaR / CVaR
    var5  = np.percentile(r, 5)
    cvar5 = r[r <= var5].mean()

    return dict(
        Sharpe=round(sharpe,3), Sortino=round(sortino,3),
        Calmar=round(calmar,3), TotalRet=round(total_ret*100,2),
        AnnRet=round(ann_ret*100,2), AnnVol=round(ann_vol*100,2),
        MaxDD=round(max_dd*100,2),
        WinRate=round(win_rate*100,2), AvgWin=round(avg_win*100,4),
        AvgLoss=round(avg_loss*100,4), WLRatio=round(wl_ratio,3),
        LongDays=int(long_d), ShortDays=int(short_d), FlatDays=int(flat_d),
        AvgHold=round(avg_hold,1), Turnover=round(turnover*100,2),
        TimeUnderwater=round(time_uw*100,1),
        VaR5=round(var5*100,3), CVaR5=round(cvar5*100,3),
        Skew=round(r.skew(),3), Kurt=round(r.kurtosis(),3),
    )

def metrics_table(mask, label=''):
    rows = []
    # Buy & Hold
    m = metrics(BH, mask)
    m['Signal'] = 'Buy & Hold'
    m['Group'] = 'Benchmark'
    rows.append(m)
    for grp, keys in SIG_GROUPS.items():
        for k in keys:
            m = metrics(ALL_SIGS[k], mask)
            m['Signal'] = k
            m['Group'] = grp
            rows.append(m)
    df_out = pd.DataFrame(rows).set_index('Signal')
    return df_out

