# Diversification Ratio = weighted avg vol / portfolio vol
def diversification_ratio(sig_keys):
    rets = ens_ret[sig_keys]
    w_n  = np.ones(len(sig_keys)) / len(sig_keys)
    w_avg_vol = np.sqrt(np.diag(rets.cov().values * 252)) @ w_n
    port_vol  = np.sqrt(w_n @ (rets.cov().values * 252) @ w_n)
    return w_avg_vol / port_vol if port_vol > 0 else 1

