# Pairwise correlation - find high correlations & potential redundancy
def high_corr_pairs(corr, threshold=0.50):
    pairs = []
    cols = [c for c in corr.columns if c != 'Buy & Hold']
    for i in range(len(cols)):
        for j in range(i+1, len(cols)):
            v = corr.loc[cols[i], cols[j]]
            if abs(v) >= threshold:
                pairs.append({'Signal A': cols[i], 'Signal B': cols[j], 'Corr': round(v,3)})
    return pd.DataFrame(pairs).sort_values('Corr', ascending=False)

