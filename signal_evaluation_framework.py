"""## 11 · Lookahead Bias Checks"""

def check_lookahead(name, sig):
    results = {}

    # Test 1: same-day correlation (signal vs same-day return, no shift)
    # A clean signal should have near-zero same-day correlation
    # We look at the UNSHIFTED signal vs current-day return
    # (the shift(1) should already be inside gld_signals)
    same_day_corr = sig.corr(full_df['Ret'])
    results['SameDayCorr'] = round(same_day_corr, 4)
    results['SameDayCorr_Flag'] = '❌ HIGH' if abs(same_day_corr) > 0.15 else '✅ OK'

    # Test 2: next-day return correlation (should be positive for good signals)
    fwd_corr = sig.corr(full_df['Ret'].shift(-1))
    results['FwdCorr'] = round(fwd_corr, 4)
    results['FwdCorr_Flag'] = '✅ OK' if abs(fwd_corr) < 0.30 else '⚠️ HIGH'

    # Test 3: Sharpe without shift (a real lookahead signal explodes here)
    r_no_shift = sig * full_df['Ret']   # no extra shift — exploits lookahead if present
    sh_no_shift = r_no_shift.mean() / r_no_shift.std() * np.sqrt(252) if r_no_shift.std() > 0 else 0
    results['Sharpe_NoShift'] = round(sh_no_shift, 3)
    results['NoShift_Flag'] = ('❌ SUSPECT (Sharpe > 3 without shift suggests lookahead)'
                                if sh_no_shift > 3 else '✅ OK')

    # Test 4: NaN rate
    nan_rate = sig.isna().mean()
    results['NaN_Rate'] = round(nan_rate, 4)
    results['NaN_Flag'] = '⚠️ HIGH' if nan_rate > 0.10 else '✅ OK'

    return results

