# Cumulative returns & drawdown for train-sample
def plot_equity(sigs_dict, mask, title, log=True):
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(16, 10),
                                    gridspec_kw={'height_ratios': [3, 1]})
    colors = plt.cm.tab10.colors
    bh_r = strat_ret(BH, mask).fillna(0)
    bh_cum = (1 + bh_r).cumprod()
    ax1.plot(bh_cum.index, bh_cum.values, 'k--', lw=2.5, label='Buy & Hold', alpha=0.7)

    for i, (name, sig) in enumerate(sigs_dict.items()):
        r = strat_ret(sig, mask).fillna(0)
        cum = (1 + r).cumprod()
        ax1.plot(cum.index, cum.values, lw=1.8,
                 color=colors[i % len(colors)], label=name, alpha=0.85)

    if log:
        ax1.set_yscale('log')
    ax1.set_title(title, fontweight='bold')
    ax1.set_ylabel('Cumulative Return (log)' if log else 'Cumulative Return')
    ax1.legend(fontsize=8, ncol=3)
    ax1.grid(True, alpha=0.3)

    # Drawdown panel
    for i, (name, sig) in enumerate(sigs_dict.items()):
        r = strat_ret(sig, mask).fillna(0)
        cum = (1 + r).cumprod()
        dd  = (cum / cum.cummax()) - 1
        ax2.fill_between(dd.index, dd.values, 0,
                         color=colors[i % len(colors)], alpha=0.25)
    ax2.set_ylabel('Drawdown')
    ax2.set_ylim(-1, 0.05)
    ax2.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.show()

