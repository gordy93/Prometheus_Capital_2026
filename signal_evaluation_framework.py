"""## 7 · Rolling Performance"""

def rolling_sharpe(sig, window=252):
    r = (sig * full_df['Ret']).fillna(0)
    roll_mean = r.rolling(window).mean()
    roll_std  = r.rolling(window).std()
    return (roll_mean / roll_std * np.sqrt(252)).replace([np.inf,-np.inf], np.nan)

